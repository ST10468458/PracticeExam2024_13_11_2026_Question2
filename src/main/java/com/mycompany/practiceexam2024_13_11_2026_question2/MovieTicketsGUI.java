    private void process() {
        // Read
        String movieName = cmb_Movies.getSelectedItem().toString();
        
        int quantity;
        double price;
        
        try{
            quantity = Integer.parseInt(txtF_NumOfTickets.getText().trim());
            price = Double.parseDouble(txtF_Price.getText().trim());
        }
        catch (NumberFormatException e) {
            JOptionPane.showMessageDialog (this, "Please enter a valid number of tickets and price");
            return;
        }
        
        // Validate data
        MovieTicketData orderData = new MovieTicketData(movieName, quantity, price);
        MovieTickets tickets = new MovieTickets();
        if (!tickets.ValidateData(orderData)) {
            JOptionPane.showMessageDialog (this, "Invalid data:\n"
                    + "- Movie ticket name cannot be empty\n"
                    + "- Movie ticket price cannot be less than or equal to zero (o)\n"
                    + "- Number of movie tickets cannot be less than or equal to zero (0)");
            return;
        }
        
        // The total
        double total = tickets.CalculateTotalTicketPrice(quantity, price);
        
        // Build the report
        String reportText = ("MOVIE NAME: " + movieName + "\n"
                                       + "NUMBER OF TICKETS: " + quantity + "\n"
                                       + "MOVIE TICKET PRICE: R" + String.format("%.2f", price) + "\n"
                                       + "TOTAL TICKET PRICE: R" + String.format("%.2f", total));
        
        //Display
        txtArea_Report.setText(reportText);
        
        // Save
        txtArea_Report.setText(reportText);
        
        try (FileWriter writer = new FileWriter ("report.txt")) {
            writer.write (reportText);
        } catch (IOException e) {
            JOptionPane.showMessageDialog (this, "could not save: " + e.getMessage());
        }
        
        
        
    }
    
    
    
    

